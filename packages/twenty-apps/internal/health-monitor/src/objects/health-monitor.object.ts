const numberField = (
  universalIdentifier: string,
  name: string,
  label: string,
  defaultValue: number,
) => ({
  universalIdentifier,
  type: FieldType.NUMBER as const,
  name,
  label,
  icon: 'IconNumber',
  isNullable: false,
  defaultValue,
});

const booleanField = (
  universalIdentifier: string,
  name: string,
  label: string,
  defaultValue: boolean,
) => ({
  universalIdentifier,
  type: FieldType.BOOLEAN as const,
  name,
  label,
  icon: 'IconToggleLeft',
  isNullable: false,
  defaultValue,
});

